import type { RuntimeBundle } from "../abi.js";
import { formatPow10x128Data } from "../data/pow10-data.js";
import { Native } from "./native.js";

/** Number::toString for doubles. Integers below 2^53 are written directly.
 * Every other finite non-zero value gets its shortest round-trip digits from
 * Schubfach (Raffaello Giulietti, "The Schubfach way to render doubles", the
 * algorithm of Java's DoubleToDecimal): with x = c * 2^q and k = floor(log10
 * of 2^q), or of 3/4 * 2^q when the lower neighbour is closer (powers of two),
 * the ends of the rounding interval and x itself are scaled by 10^-k with a
 * 128-bit power of ten g rounded up, each product rounded to odd. Among the
 * decimals in the interval it takes the one with one digit less if there is
 * one, else the closest (ties to an even significand): the n, k, s that
 * Number::toString asks for. The digits are then laid out as fixed or exponent
 * text in the frame and copied into a string of exact length.
 */
// The table rt.formatPow10x128 starts at 10^POW10_MIN.
const POW10_MIN = -292;
export function emitFormat(b: RuntimeBundle): void {
    // g(e) for 10^e, e in -292..324: floor(10^e * 2^(127 -
    // floor(log2(10^e)))) + 1, in [2^127, 2^128), as a low and a high qword.
    // Generated by scripts/generate-pow10-tables.mjs.
    b.fragments.push({
        name: "rt.formatPow10x128",
        section: ".rdata",
        alignment: 16,
        bytes: new Uint8Array(formatPow10x128Data),
        fixups: [],
        symbols: {},
    });
    // 10^1..10^16 as qwords, and "00".."99" as two UTF-16 units each.
    {
        const powers = new Uint8Array(16 * 8),
            view = new DataView(powers.buffer);
        for (let i = 0; i < 16; i++)
            view.setBigUint64(i * 8, 10n ** BigInt(i + 1), true);
        b.fragments.push({
            name: "rt.formatPow10",
            section: ".rdata",
            alignment: 8,
            bytes: powers,
            fixups: [],
            symbols: {},
        });
        const pairs = new Uint8Array(100 * 4),
            pairView = new DataView(pairs.buffer);
        for (let i = 0; i < 100; i++) {
            pairView.setUint16(i * 4, 48 + Math.floor(i / 10), true);
            pairView.setUint16(i * 4 + 2, 48 + (i % 10), true);
        }
        b.fragments.push({
            name: "rt.formatDigitPairs",
            section: ".rdata",
            alignment: 8,
            bytes: pairs,
            fixups: [],
            symbols: {},
        });
    }
    // The digits (reversed, a byte each) and the text are built in the frame:
    // the digits from rsp+360, the text from rsp+400 (a length qword and at
    // most 25 UTF-16 units, "-0.000001" and 17 digits).
    const f = new Native("rt.formatNumber", 360 + 128),
        a = f.a;
    // Integers below 2^53 in magnitude (and -0, which prints as "0"): count
    // the digits, allocate the exact length once and write the digits right
    // to left, two at a time from rt.formatDigitPairs, dividing by 100 with
    // a reciprocal multiply: n / 100 = ((n >> 2) * 0x28F5C28F5C28F5C3) >> 66,
    // exact for every u64. The sign comes from the integer, not the double.
    a.movqFromXmm("r12", "xmm0");
    a.mov("rax", 0x7fffffffffffffffn);
    a.and("r12", "rax");
    a.movqToXmm("xmm1", "r12");
    a.mov("rax", 0x4340000000000000n);
    a.movqToXmm("xmm4", "rax");
    a.ucomisd("xmm1", "xmm4");
    a.jcc("p", "fmt.general");
    a.jcc("ae", "fmt.general");
    a.cvttsd2si("r12", "xmm0");
    a.cvtsi2sd("xmm1", "r12");
    a.ucomisd("xmm0", "xmm1");
    a.jcc("ne", "fmt.general");
    // RBX = 1 for a negative integer, R12 = its magnitude.
    a.mov("rbx", "r12");
    a.shr("rbx", 63);
    a.mov("rax", "r12");
    a.sar("rax", 63);
    a.xor("r12", "rax");
    a.sub("r12", "rax");
    // R13 = digit count: one plus the powers 10^1..10^16 not above R12.
    a.mov("r13", 1);
    a.lea("r11", { rip: "rt.formatPow10" });
    a.label("fmt.intCount");
    a.load("rax", { base: "r11" });
    a.cmp("r12", "rax");
    a.jcc("b", "fmt.intCounted");
    a.add("r13", 1);
    a.add("r11", 8);
    a.jmp("fmt.intCount");
    a.label("fmt.intCounted");
    a.mov("r15", "r13");
    a.add("r15", "rbx");
    a.mov("rcx", "r15");
    a.shl("rcx", 1);
    a.add("rcx", 8);
    a.call("rt.allocRaw");
    a.mov("r14", "rax");
    a.store({ base: "r14" }, "r15");
    // The minus sign goes first; without one the leading digit overwrites it.
    a.mov("rax", 45);
    a.store({ base: "r14", disp: 8 }, "rax", 16);
    a.lea("rdi", { base: "r14", disp: 8 });
    a.add("rdi", "r15");
    a.add("rdi", "r15");
    a.lea("rsi", { rip: "rt.formatDigitPairs" });
    a.mov("r8", 100);
    a.mov("r9", 0x28f5c28f5c28f5c3n);
    a.label("fmt.intPairs");
    a.cmp("r12", "r8");
    a.jcc("b", "fmt.intLast");
    a.mov("rax", "r12");
    a.shr("rax", 2);
    a.mul("r9");
    a.shr("rdx", 2);
    a.mov("r10", "rdx");
    a.imul("r10", "r8");
    a.sub("r12", "r10");
    a.shl("r12", 2);
    a.add("r12", "rsi");
    a.load("rax", { base: "r12" }, 32);
    a.sub("rdi", 4);
    a.store({ base: "rdi" }, "rax", 32);
    a.mov("r12", "rdx");
    a.jmp("fmt.intPairs");
    a.label("fmt.intLast");
    a.cmp("r12", 10);
    a.jcc("b", "fmt.intSingle");
    a.shl("r12", 2);
    a.add("r12", "rsi");
    a.load("rax", { base: "r12" }, 32);
    a.store({ base: "rdi", disp: -4 }, "rax", 32);
    a.mov("rax", "r14");
    a.jmp("fmt.return");
    a.label("fmt.intSingle");
    a.add("r12", 48);
    a.store({ base: "rdi", disp: -2 }, "r12", 16);
    a.mov("rax", "r14");
    a.jmp("fmt.return");
    a.label("fmt.general");
    a.movqFromXmm("r12", "xmm0");
    f.set(0, "r12");
    a.mov("rax", 0x7fffffffffffffffn);
    a.and("r12", "rax");
    a.lea("rax", { base: "rsp", disp: 360 });
    f.set(2, "rax");
    a.lea("rax", { base: "rsp", disp: 400 });
    f.set(4, "rax");
    a.lea("r15", { base: "rax", disp: 8 });
    a.mov("rax", 0x7ff0000000000000n);
    a.cmp("r12", "rax");
    a.jcc("a", "fmt.nan");
    a.jcc("e", "fmt.infinity");
    a.test("r12", "r12");
    a.jcc("e", "fmt.zero");
    // Schubfach. RSI = c, R9 = q, RBX = 1 when the lower neighbour is closer
    // (a power of two above the smallest normal): the interval is asymmetric.
    a.mov("r13", "r12");
    a.shr("r13", 52);
    a.mov("r8", 0xfffffffffffffn);
    a.and("r8", "r12");
    a.xor("rbx", "rbx");
    a.test("r13", "r13");
    a.jcc("e", "fmt.subnormal");
    a.mov("rsi", 0x10000000000000n);
    a.or("rsi", "r8");
    a.mov("r9", "r13");
    a.sub("r9", 1075);
    a.test("r8", "r8");
    a.jcc("ne", "fmt.scale");
    a.cmp("r13", 1);
    a.jcc("be", "fmt.scale");
    a.mov("rbx", 1);
    a.jmp("fmt.scale");
    a.label("fmt.subnormal");
    a.mov("rsi", "r8");
    a.mov("r9", -1074);
    // R13 = k = (q * 1262611 - 524031 * RBX) >> 22, floor(log10(2^q)) or
    // floor(log10(3/4 * 2^q)). RCX = h = q + floor(log2(10^-k)) + 1, 1..4,
    // with floor(log2(10^e)) = (e * 1741647) >> 19.
    a.label("fmt.scale");
    a.mov("r13", 1262611);
    a.imul("r13", "r9");
    a.test("rbx", "rbx");
    a.jcc("e", "fmt.symmetric");
    a.sub("r13", 524031);
    a.label("fmt.symmetric");
    a.sar("r13", 22);
    a.mov("rcx", "r13");
    a.neg("rcx");
    a.mov("rax", 1741647);
    a.imul("rcx", "rax");
    a.sar("rcx", 19);
    a.add("rcx", "r9");
    a.add("rcx", 1);
    // R11 and R14 = the low and high qwords of g(-k).
    a.mov("rax", "r13");
    a.neg("rax");
    a.sub("rax", POW10_MIN);
    a.shl("rax", 4);
    a.lea("r11", { rip: "rt.formatPow10x128" });
    a.add("r11", "rax");
    a.load("r14", { base: "r11", disp: 8 });
    a.load("r11", { base: "r11" });
    // RDI = 1 when c is odd: the ends of the interval are then excluded.
    a.mov("rdi", "rsi");
    a.and("rdi", 1);
    // R10 = vbl, R12 = vb, RSI = vbr: (4c - 2 + RBX, 4c, 4c + 2) << h times g,
    // the bits above 2^128 of the product, rounded to odd.
    a.mov("r10", "rsi");
    a.shl("r10", 2);
    a.sub("r10", 2);
    a.add("r10", "rbx");
    a.shl("r10", "cl");
    roundToOdd("r10");
    a.mov("r12", "rsi");
    a.shl("r12", 2);
    a.shl("r12", "cl");
    roundToOdd("r12");
    a.shl("rsi", 2);
    a.add("rsi", 2);
    a.shl("rsi", "cl");
    roundToOdd("rsi");
    // R10 = lower, RSI = upper (both inclusive), RBX = s = vb / 4.
    a.add("r10", "rdi");
    a.sub("rsi", "rdi");
    a.mov("rbx", "r12");
    a.shr("rbx", 2);
    // One digit less: s' = s / 10. At most one of 40s' and 40(s' + 1) is in
    // the interval; when exactly one is, it is the answer.
    a.cmp("rbx", 10);
    a.jcc("b", "fmt.full");
    a.mov("rax", "rbx");
    a.mov("r9", 0xcccccccccccccccdn);
    a.mul("r9");
    a.shr("rdx", 3);
    a.mov("rax", 40);
    a.imul("rax", "rdx");
    a.cmp("r10", "rax");
    a.jcc("a", "fmt.shortHigh");
    a.add("rax", 40);
    a.cmp("rax", "rsi");
    a.jcc("be", "fmt.full");
    a.mov("r12", "rdx");
    a.add("r13", 1);
    a.jmp("fmt.selected");
    a.label("fmt.shortHigh");
    a.add("rax", 40);
    a.cmp("rax", "rsi");
    a.jcc("a", "fmt.full");
    a.lea("r12", { base: "rdx", disp: 1 });
    a.add("r13", 1);
    a.jmp("fmt.selected");
    // Full length: s or s + 1, whichever is in the interval; when both are,
    // the one closer to vb, ties to even.
    a.label("fmt.full");
    a.mov("rax", "rbx");
    a.shl("rax", 2);
    a.cmp("r10", "rax");
    a.jcc("a", "fmt.up");
    a.add("rax", 4);
    a.cmp("rax", "rsi");
    a.jcc("a", "fmt.down");
    a.sub("rax", 2);
    a.cmp("r12", "rax");
    a.jcc("a", "fmt.up");
    a.jcc("b", "fmt.down");
    a.mov("rax", "rbx");
    a.and("rax", 1);
    a.jcc("ne", "fmt.up");
    a.label("fmt.down");
    a.mov("r12", "rbx");
    a.jmp("fmt.selected");
    a.label("fmt.up");
    a.lea("r12", { base: "rbx", disp: 1 });
    // R12 = digits, R13 = decimal exponent: drop trailing zeros, then write
    // the digits reversed, dividing by 10 with a reciprocal multiply:
    // n / 10 = (n * 0xCCCCCCCCCCCCCCCD) >> 67, exact for every u64.
    a.label("fmt.selected");
    a.mov("r10", 0xcccccccccccccccdn);
    a.mov("r11", 10);
    a.label("fmt.strip");
    a.mov("rax", "r12");
    a.mul("r10");
    a.shr("rdx", 3);
    a.mov("rax", "rdx");
    a.imul("rax", "r11");
    a.cmp("rax", "r12");
    a.jcc("ne", "fmt.qdigits");
    a.mov("r12", "rdx");
    a.add("r13", 1);
    a.jmp("fmt.strip");
    a.label("fmt.qdigits");
    f.get("rdi", 2);
    a.label("fmt.qloop");
    a.mov("rax", "r12");
    a.mul("r10");
    a.shr("rdx", 3);
    a.mov("rax", "rdx");
    a.imul("rax", "r11");
    a.sub("r12", "rax");
    a.add("r12", 48);
    a.store({ base: "rdi" }, "r12", 8);
    a.add("rdi", 1);
    a.mov("r12", "rdx");
    a.test("r12", "r12");
    a.jcc("ne", "fmt.qloop");
    f.get("rax", 2);
    a.mov("r14", "rdi");
    a.sub("r14", "rax");
    a.add("r13", "r14"); // K = digits + scale
    f.get("rax", 0);
    a.shr("rax", 63);
    a.test("rax", "rax");
    a.jcc("e", "fmt.layout");
    a.mov("rax", 45);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.label("fmt.layout");
    a.cmp("r13", 0);
    a.jcc("le", "fmt.small");
    a.cmp("r13", 21);
    a.jcc("g", "fmt.scientific");
    a.mov("r12", "r13");
    a.label("fmt.fixedloop");
    a.cmp("r14", 0);
    a.jcc("le", "fmt.pad");
    a.sub("rdi", 1);
    a.load("rax", { base: "rdi" }, 8);
    a.sub("r14", 1);
    a.jmp("fmt.fixedwrite");
    a.label("fmt.pad");
    a.mov("rax", 48);
    a.label("fmt.fixedwrite");
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r12", 1);
    a.jcc("ne", "fmt.fixedloop");
    a.test("r14", "r14");
    a.jcc("e", "fmt.finish");
    a.mov("rax", 46);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.jmp("fmt.tail");
    a.label("fmt.small");
    a.cmp("r13", -6);
    a.jcc("le", "fmt.scientific");
    a.mov("rax", 48);
    a.store({ base: "r15" }, "rax", 16);
    a.mov("rax", 46);
    a.store({ base: "r15", disp: 2 }, "rax", 16);
    a.add("r15", 4);
    a.neg("r13");
    a.test("r13", "r13");
    a.jcc("e", "fmt.tail");
    a.label("fmt.leading");
    a.mov("rax", 48);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r13", 1);
    a.jcc("ne", "fmt.leading");
    a.label("fmt.tail");
    a.sub("rdi", 1);
    a.load("rax", { base: "rdi" }, 8);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r14", 1);
    a.jcc("ne", "fmt.tail");
    a.jmp("fmt.finish");
    a.label("fmt.scientific");
    a.sub("rdi", 1);
    a.load("rax", { base: "rdi" }, 8);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r14", 1);
    a.jcc("e", "fmt.exponent");
    a.mov("rax", 46);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.label("fmt.scitail");
    a.sub("rdi", 1);
    a.load("rax", { base: "rdi" }, 8);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r14", 1);
    a.jcc("ne", "fmt.scitail");
    a.label("fmt.exponent");
    a.mov("rax", 101);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.sub("r13", 1);
    a.mov("rax", 43);
    a.cmp("r13", 0);
    a.jcc("ge", "fmt.expsign");
    a.mov("rax", 45);
    a.neg("r13");
    a.label("fmt.expsign");
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    f.get("rdi", 2);
    a.mov("rax", "r13");
    a.mov("r10", 10);
    a.xor("r14", "r14");
    a.label("fmt.expdivide");
    a.xor("rdx", "rdx");
    a.div("r10");
    a.add("rdx", 48);
    a.store({ base: "rdi" }, "rdx", 8);
    a.add("rdi", 1);
    a.add("r14", 1);
    a.test("rax", "rax");
    a.jcc("ne", "fmt.expdivide");
    a.jmp("fmt.tail");
    a.label("fmt.infinity");
    f.get("rax", 0);
    a.shr("rax", 63);
    a.test("rax", "rax");
    a.jcc("e", "fmt.inftext");
    a.mov("rax", 45);
    a.store({ base: "r15" }, "rax", 16);
    a.add("r15", 2);
    a.label("fmt.inftext");
    writeText("Infinity");
    a.jmp("fmt.finish");
    a.label("fmt.nan");
    writeText("NaN");
    a.jmp("fmt.finish");
    a.label("fmt.zero");
    writeText("0");
    // The text was built in the frame: allocate the string of exactly that length and copy it.
    a.label("fmt.finish");
    f.get("rax", 4);
    a.sub("r15", "rax");
    a.sub("r15", 8);
    a.shr("r15", 1);
    a.mov("r13", "r15");
    a.mov("rcx", "r13");
    a.shl("rcx", 1);
    a.add("rcx", 8);
    a.call("rt.allocRaw");
    a.mov("r14", "rax");
    a.store({ base: "rax" }, "r13");
    f.get("rsi", 4);
    a.add("rsi", 8);
    a.lea("rdi", { base: "rax", disp: 8 });
    a.label("fmt.copy");
    a.test("r13", "r13");
    a.jcc("e", "fmt.copied");
    a.load("rax", { base: "rsi" }, 16);
    a.store({ base: "rdi" }, "rax", 16);
    a.add("rsi", 2);
    a.add("rdi", 2);
    a.sub("r13", 1);
    a.jmp("fmt.copy");
    a.label("fmt.copied");
    a.mov("rax", "r14");
    a.label("fmt.return");
    f.end(b);
    function writeText(s: string) {
        for (const c of s) {
            a.mov("rax", c.charCodeAt(0));
            a.store({ base: "r15" }, "rax", 16);
            a.add("r15", 2);
        }
    }
    // r = floor(r * g / 2^128) for g = R14:R11, made odd when the product's
    // middle qword is above 1 (inexact, allowing for g being rounded up). The
    // product is y * 2^64 + x0 with y = r * hi + (r * lo >> 64), so the result
    // is y >> 64 and the middle qword is y's low one. Uses RAX, RDX and R9.
    function roundToOdd(r: "r10" | "r12" | "rsi") {
        const noCarry = a.unique("fmt.noCarry"),
            exact = a.unique("fmt.exact");
        a.mov("rax", r);
        a.mul("r11");
        a.mov("r9", "rdx");
        a.mov("rax", r);
        a.mul("r14");
        a.add("rax", "r9");
        a.jcc("ae", noCarry);
        a.add("rdx", 1);
        a.label(noCarry);
        a.cmp("rax", 1);
        a.jcc("be", exact);
        a.or("rdx", 1);
        a.label(exact);
        a.mov(r, "rdx");
    }
}
