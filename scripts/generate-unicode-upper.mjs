import {writeFileSync} from 'node:fs';

// Each 16-byte record is: code point (u32), UTF-16 length (u32), up to
// three UTF-16 code units (u16 each), and two padding bytes. Records are
// sorted for binary search by the native runtime.
const records=[];
for(let cp=0;cp<=0x10ffff;cp++){
  if(cp>=0xd800&&cp<=0xdfff)continue;
  const original=String.fromCodePoint(cp);
  const upper=original.toUpperCase();
  if(upper===original)continue;
  if(upper.length>3)throw new Error(`Uppercase expansion too long: U+${cp.toString(16)}`);
  const record=Buffer.alloc(16);
  record.writeUInt32LE(cp,0);
  record.writeUInt32LE(upper.length,4);
  for(let i=0;i<upper.length;i++)record.writeUInt16LE(upper.charCodeAt(i),8+i*2);
  records.push(record);
}
const base64=Buffer.concat(records).toString('base64');
const chunks=base64.match(/.{1,120}/g)??[];
const source=`// Generated by scripts/generate-unicode-upper.mjs with Unicode ${process.versions.unicode}.\n`+
  `// Keep this fixed so compiled programs behave the same on every host.\n`+
  `export const unicodeUpperCount=${records.length};\n`+
  `export const unicodeUpperData=Buffer.from(\n`+
  chunks.map(chunk=>`  '${chunk}'`).join(' +\n')+
  `,\n  'base64',\n);\n`;
writeFileSync(new URL('../src/runtime/unicode-upper-data.ts',import.meta.url),source);
console.log(`Generated ${records.length} uppercase mappings for Unicode ${process.versions.unicode}`);
