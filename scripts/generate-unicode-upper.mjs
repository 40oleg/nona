import {writeFileSync} from 'node:fs';

// Each 16-byte record is: code point (u32), UTF-16 length (u32), up to
// three UTF-16 code units (u16 each), and two padding bytes. Records are
// sorted for binary search by the native runtime.
let source=`// Generated by scripts/generate-unicode-upper.mjs with Unicode ${process.versions.unicode}.\n`+
  `// Keep this fixed so compiled programs behave the same on every host.\n`;
for(const [name,convert] of [['Upper',s=>s.toUpperCase()],['Lower',s=>s.toLowerCase()]]){
  const records=[];
  for(let cp=0;cp<=0x10ffff;cp++){
    if(cp>=0xd800&&cp<=0xdfff)continue;
    const original=String.fromCodePoint(cp);
    const converted=convert(original);
    if(converted===original)continue;
    if(converted.length>3)throw new Error(`${name}case expansion too long: U+${cp.toString(16)}`);
    const record=Buffer.alloc(16);
    record.writeUInt32LE(cp,0);
    record.writeUInt32LE(converted.length,4);
    for(let i=0;i<converted.length;i++)record.writeUInt16LE(converted.charCodeAt(i),8+i*2);
    records.push(record);
  }
  const base64=Buffer.concat(records).toString('base64');
  const chunks=base64.match(/.{1,120}/g)??[];
  source+=`export const unicode${name}Count=${records.length};\n`+
    `export const unicode${name}Data=Buffer.from(\n`+
    chunks.map(chunk=>`  '${chunk}'`).join(' +\n')+
    `,\n  'base64',\n);\n`;
  console.log(`Generated ${records.length} ${name.toLowerCase()}case mappings for Unicode ${process.versions.unicode}`);
}
for(const [name,pattern] of [['Cased',/\p{Cased}/u],['CaseIgnorable',/\p{Case_Ignorable}/u]]){
  const ranges=[];
  let begin=-1;
  for(let cp=0;cp<=0x110000;cp++){
    const matches=cp<=0x10ffff&&pattern.test(String.fromCodePoint(cp));
    if(matches&&begin<0)begin=cp;
    if(!matches&&begin>=0){
      const record=Buffer.alloc(8);
      record.writeUInt32LE(begin,0);record.writeUInt32LE(cp-1,4);
      ranges.push(record);begin=-1;
    }
  }
  const base64=Buffer.concat(ranges).toString('base64');
  const chunks=base64.match(/.{1,120}/g)??[];
  source+=`export const unicode${name}Count=${ranges.length};\n`+
    `export const unicode${name}Data=Buffer.from(\n`+
    chunks.map(chunk=>`  '${chunk}'`).join(' +\n')+
    `,\n  'base64',\n);\n`;
  console.log(`Generated ${ranges.length} ${name} ranges`);
}
writeFileSync(new URL('../src/runtime/unicode-upper-data.ts',import.meta.url),source);
