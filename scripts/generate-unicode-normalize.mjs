import {writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const version='17.0.0';
if(process.versions.unicode!=='17.0')throw new Error('Node with Unicode 17 required');
const response=await fetch('https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt');
if(!response.ok)throw new Error(`UnicodeData download: HTTP ${response.status}`);
const bytes=Buffer.from(await response.arrayBuffer());
const hash=createHash('sha256').update(bytes).digest('hex');
if(hash!=='2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c')throw new Error(`Unexpected UnicodeData SHA-256: ${hash}`);
const ucd=bytes.toString('utf8');
const ccc=[];const pairs=[];
for(const line of ucd.split(/\r?\n/)){
 if(!line||line.startsWith('#'))continue;
 const f=line.split(';'),cp=parseInt(f[0],16),cls=Number(f[3]);
 if(cls)ccc.push([cp,cls]);
 if(f[5]&&!f[5].startsWith('<')){
  const seq=f[5].split(' ').map(x=>parseInt(x,16));
  if(seq.length===2&&String.fromCodePoint(...seq).normalize('NFC')===String.fromCodePoint(cp))pairs.push([seq[0],seq[1],cp]);
 }
}
const maxLen=18;
const decomp={Canonical:[],Compatibility:[]};
for(let cp=0;cp<=0x10ffff;cp++){
 if(cp>=0xd800&&cp<=0xdfff)continue;
 if(cp>=0xac00&&cp<=0xd7a3)continue; // Algorithmic Hangul.
 const s=String.fromCodePoint(cp);
 for(const [kind,form] of [['Canonical','NFD'],['Compatibility','NFKD']]){
  const d=[...s.normalize(form)].map(c=>c.codePointAt(0));
  if(d.length===1&&d[0]===cp)continue;
  if(d.length>maxLen)throw new Error(`${kind} U+${cp.toString(16)} length ${d.length}`);
  decomp[kind].push([cp,d]);
 }
}
function emit(name,records,size,fill){
 const b=Buffer.alloc(records.length*size);
 records.forEach((r,i)=>fill(b,r,i*size));
 const chunks=(b.toString('base64').match(/.{1,120}/g)??[]);
 return `export const unicodeNormalize${name}Count=${records.length};\nexport const unicodeNormalize${name}Data=Buffer.from(\n${chunks.map(c=>` '${c}'`).join(' +\n')},\n 'base64',\n);\n`;
}
let out=`// Generated by scripts/generate-unicode-normalize.mjs from Unicode ${version}.\n`;
for(const k of ['Canonical','Compatibility'])out+=emit(k,decomp[k],80,(b,[cp,d],o)=>{b.writeUInt32LE(cp,o);b.writeUInt32LE(d.length,o+4);d.forEach((n,i)=>b.writeUInt32LE(n,o+8+i*4));});
out+=emit('Ccc',ccc,8,(b,[cp,cls],o)=>{b.writeUInt32LE(cp,o);b.writeUInt32LE(cls,o+4);});
pairs.sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
out+=emit('Compose',pairs,12,(b,[x,y,z],o)=>{b.writeUInt32LE(x,o);b.writeUInt32LE(y,o+4);b.writeUInt32LE(z,o+8);});
writeFileSync(new URL('../src/runtime/unicode-normalize-data.ts',import.meta.url),out);
console.log({canonical:decomp.Canonical.length,compatibility:decomp.Compatibility.length,ccc:ccc.length,pairs:pairs.length,bytes:out.length});
