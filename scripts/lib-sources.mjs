// The JavaScript built into every executable (runtime preludes, src/lib/runtime)
// and the bodies of the built-in node:* modules (src/lib/modules) are real .js
// files. scripts/build.mjs turns them into string constants before tsc runs,
// in src/lib/sources.generated.ts (not checked in), and copies them to dist.
//
// Each file is the body of a String.raw template literal: its text is the
// constant's value, byte for byte (line terminators normalized to LF as in a
// template literal). A file that contains `${...}` substitutions becomes a
// template object instead; the TypeScript module that uses it fills the
// substitutions in place with String.raw(template, ...values), in order.
import {copyFileSync,mkdirSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {dirname,join,relative} from 'node:path';

/** Every .js file below directory, sorted, as paths relative to it with '/' separators. */
function libFiles(directory,prefix=''){
  const entries=readdirSync(join(directory,prefix),{withFileTypes:true}).sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0);
  return entries.flatMap(entry=>entry.isDirectory()?libFiles(directory,prefix+entry.name+'/'):entry.name.endsWith('.js')?[prefix+entry.name]:[]);
}

/** `runtime/regexp-vm.js` -> `runtimeRegexpVm`. */
export function libSourceName(path){
  return path.replace(/\.js$/,'').replace(/[-/.]+([a-z0-9])/g,(_,c)=>c.toUpperCase());
}

/** End of a `${...}` substitution that starts at index (just after `${`). */
function skipSubstitution(text,index,file){
  let depth=0;
  for(;;){
    const c=text[index];
    if(c===undefined)throw new Error(`${file}: unterminated \${ substitution`);
    if(c==="'"||c==='"'){const quote=c;index++;while(text[index]!==quote){if(text[index]===undefined)throw new Error(`${file}: unterminated string in substitution`);if(text[index]==='\\')index++;index++;}index++;continue;}
    if(c==='{')depth++;
    else if(c==='}'){if(depth===0)return index+1;depth--;}
    index++;
  }
}

/** The raw strings of a template literal whose body is text. */
export function templateParts(text,file='template'){
  const parts=[];let start=0;
  for(let index=0;index<text.length;){
    const c=text[index];
    if(c==='\\'){index+=2;continue;}
    if(c==='`')throw new Error(`${file}: unescaped backtick at offset ${index}`);
    if(c==='$'&&text[index+1]==='{'){parts.push(text.slice(start,index));index=skipSubstitution(text,index+2,file);start=index;continue;}
    index++;
  }
  parts.push(text.slice(start));
  return parts;
}

export function generateLibSources(projectRoot){
  const source=join(projectRoot,'src','lib'),output=join(projectRoot,'dist','src','lib');
  const files=libFiles(source),names=new Map();
  let module='/** Generated by scripts/build.mjs from the .js files of src/lib; do not edit manually. */\n';
  for(const file of files){
    const name=libSourceName(file);
    if(names.has(name))throw new Error(`src/lib/${file} and src/lib/${names.get(name)} have the same name ${name}`);
    names.set(name,file);
    const text=readFileSync(join(source,file),'utf8').replace(/\r\n?/g,'\n');
    const parts=templateParts(text,'src/lib/'+file);
    module+=parts.length===1
      ?`export const ${name}:string=${JSON.stringify(text)};\n`
      :`export const ${name}:{readonly raw:readonly string[]}={raw:[${parts.map(part=>JSON.stringify(part)).join(',')}]};\n`;
  }
  const generated=join(source,'sources.generated.ts');
  let existing;try{existing=readFileSync(generated,'utf8');}catch{}
  if(existing!==module)writeFileSync(generated,module,'utf8');
  return ()=>{
    for(const file of files){
      mkdirSync(dirname(join(output,file)),{recursive:true});
      copyFileSync(join(source,file),join(output,file));
    }
    return files.map(file=>relative(projectRoot,join(output,file)));
  };
}
