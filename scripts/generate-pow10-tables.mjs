import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// The 128-bit powers of ten of rt.formatNumber (Schubfach) and rt.parseNumber
// (Eisel-Lemire). They are computed here with BigInt and committed, because the
// runtime is built by every compiler process, including the self-hosted one,
// whose BigInt arithmetic made the computation take minutes (#558).

/** g(e) for 10^e, e in -292..324: floor(10^e * 2^(127 - floor(log2(10^e))))
 * + 1, in [2^127, 2^128), as a low and a high qword (little-endian). */
export function formatPow10Table() {
    const min = -292,
        max = 324,
        bytes = Buffer.alloc((max - min + 1) * 16),
        mask = (1n << 64n) - 1n;
    for (let e = min; e <= max; e++) {
        const num = e >= 0 ? 10n ** BigInt(e) : 1n,
            den = e >= 0 ? 1n : 10n ** BigInt(-e),
            shift = 127 - ((e * 1741647) >> 19),
            g =
                (shift >= 0
                    ? (num << BigInt(shift)) / den
                    : num / (den << BigInt(-shift))) + 1n;
        if (g >> 127n !== 1n) throw new Error("format pow10 table " + e);
        bytes.writeBigUInt64LE(g & mask, (e - min) * 16);
        bytes.writeBigUInt64LE(g >> 64n, (e - min) * 16 + 8);
    }
    return bytes;
}

/** Truncated 128-bit powers of ten as in fast_float: entry q in [-342, 308]
 * (16 bytes, high qword first, each little-endian) is the 128-bit normalized
 * mantissa c of 10^q, 2^127 <= c < 2^128. For q >= 0, c is 5^q shifted until
 * it has 128 bits (truncated). For q < 0 with z = bitlength(5^-q - 1):
 * c = floor(2^(z+127) / 5^-q) + 1 when q >= -27, otherwise
 * floor(2^(2z+128) / 5^-q) + 1 halved until it has 128 bits. */
export function parsePow10Table() {
    const min = -342,
        max = 308,
        bytes = Buffer.alloc((max - min + 1) * 16),
        bits = (value) => BigInt(value.toString(2).length),
        normalize = (c) => {
            const excess = bits(c) - 128n;
            return excess >= 0n ? c >> excess : c << -excess;
        };
    for (let q = min; q <= max; q++) {
        let c;
        if (q < 0) {
            const p = 5n ** BigInt(-q),
                z = bits(p - 1n);
            c =
                q >= -27
                    ? (1n << (z + 127n)) / p + 1n
                    : normalize((1n << (2n * z + 128n)) / p + 1n);
        } else c = normalize(5n ** BigInt(q));
        if (c >> 127n !== 1n) throw new Error("parse pow10 table " + q);
        bytes.writeBigUInt64LE(c >> 64n, (q - min) * 16);
        bytes.writeBigUInt64LE(BigInt.asUintN(64, c), (q - min) * 16 + 8);
    }
    return bytes;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    let source =
        "// Generated by scripts/generate-pow10-tables.mjs; do not edit by hand.\n";
    for (const [name, bytes] of [
        ["formatPow10x128", formatPow10Table()],
        ["parsePow10x128", parsePow10Table()],
    ]) {
        const chunks = bytes.toString("base64").match(/.{1,120}/g) ?? [];
        source +=
            `export const ${name}Data=Buffer.from(\n` +
            chunks.map((chunk) => `  '${chunk}'`).join(" +\n") +
            `,\n  'base64',\n);\n`;
    }
    writeFileSync(
        fileURLToPath(
            new URL("../src/runtime/data/pow10-data.ts", import.meta.url),
        ),
        source,
    );
    console.log("Generated src/runtime/data/pow10-data.ts");
}
